'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
const css=fs.readFileSync(path.join(root,'css/obsada-module.css'),'utf8');
const planning=html.slice(html.indexOf("<template v-else-if=\"obsada.state.tab==='planning'\">"),html.indexOf("obsada.state.tab==='history'",html.indexOf("<template v-else-if=\"obsada.state.tab==='planning'\">"))>0?html.indexOf("obsada.state.tab==='history'",html.indexOf("<template v-else-if=\"obsada.state.tab==='planning'\">")):html.indexOf("<template v-else-if=\"obsada.state.tab==='planning'\">")+15000);
assert(planning.includes('obs-plan-controlbar'),'Compact control bar exists');
assert(!planning.includes('obs-confirm-panel'),'No big automatic status banner in planning');
assert(!planning.includes('obsadaPlan.finishedHours'),'No finished-hour totals in planning');
assert(!planning.includes('obsadaPlan.futureHours'),'No future-hour totals in planning');
assert(planning.includes('obsadaPlan.currentPeopleCount'),'Selected-hour counters retained');
assert(planning.includes('obs-team-template-details'),'Team management is collapsible');
assert(!planning.includes("'Изменить название'"),'No duplicate rename action');
assert(planning.includes('obsadaPlan.renameTeamTemplate()'),'One rename action retained');
assert(planning.includes('obsadaPlan.saveTeamTemplate()'),'Save team retained');
assert(planning.includes('obsadaPlan.loadTeamTemplate()'),'Apply team retained');
assert(planning.includes('obsadaPlan.deleteTeamTemplate()'),'Delete team retained');
assert(css.includes('.obs-plan-controlbar'));
assert(js.includes("obsada:{label:'Obsada',color:'#b94f5c',bg:'rgba(185,79,92,.12)'}"),'Only changelog module badge changed to red');
console.log('PASS: compact planning header, no plan-hour totals, single rename control, Obsada changelog accent');
