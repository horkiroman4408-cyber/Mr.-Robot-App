'use strict';
const assert=require('node:assert/strict');
const p=require('../js/obsada-planner.js');
const person='36001214';
const entry=(date,process='AUDYT',source='Listopad')=>({date,login:person,process,hours:8,source,sourceType:'main',raw:`${process} (8h)`});
const imported=[entry('2026-11-02'),entry('2026-11-02','SCALANIE')];
let next=p.replaceImported([],imported,['Listopad'],r=>r.date);
assert.equal(next.length,2,'two processes on one day must survive import');
next=p.replaceImported(next,imported,['Listopad'],r=>r.date);
assert.equal(next.length,2,'reimport must not duplicate');
next=p.replaceImported(next,[entry('2026-11-02','METKI')],['Listopad'],r=>r.date);
assert.deepEqual(next.map(r=>r.process),['METKI'],'updated day replaces previous assignments');
next=p.replaceImported(next,[entry('2027-11-02')],['Listopad'],r=>r.date);
assert.equal(next.length,2,'new year must preserve the previous year');
const night=p.makeSlots('2026-11-14','18-06');
assert.equal(night.length,12);assert.equal(night[0].from,'18:00');assert.equal(night[11].to,'06:00');
const plan=p.applyAssignment([],{day:'2026-11-14',shift:'18-06',from:0,to:2,login:person,process:'AUDYT'});
assert.equal(plan.length,2);assert.ok(plan.every(r=>r.day==='2026-11-14'));
console.log('PASS Obsada local history import idempotence, edit, year preservation and night shift');
