'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const oldTimer=global.setInterval;global.setInterval=()=>0;
const root=path.join(__dirname,'..');
const planner=require('../js/obsada-planner.js');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'css/obsada-module.css'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const obj=planner.create({reactive:x=>x,computed:f=>({get value(){return f()}}),roster:()=>[],source:()=>({employees:[],intervals:[]}),sourceName:()=>'',language:()=> 'ru'});
try{
 const day='2099-11-17';obj.state.day=day;
 obj.state.shiftTeams={[`${day}|14-22`]:['LPP'],[`${day}|18-06`]:['AGENCY']};
 obj.state.shift='14-22';
 const stamps=h=>planner.makeSlots(day,'14-22')[h].start;
 const hour17=stamps(3),hour18=stamps(4),hour21=stamps(7);
 assert.equal(obj.chooseSharedHour(hour17),true);
 assert.equal(obj.state.shift,'14-22');
 assert.equal(obj.chooseSharedHour(hour18),true);
 assert.equal(obj.state.shift,'18-06','should switch at start of the later team even in overlap');
 assert.equal(obj.selectedSlot.value.start,hour18);
 assert.deepEqual(obj.sharedTimeline.value.find(h=>h.start===hour18).shifts.sort(),['14-22','18-06']);
 assert.equal(obj.chooseSharedHour(hour21),true);
 assert.equal(obj.state.shift,'18-06');
 assert.equal(obj.chooseSharedHour(hour17),true);
 assert.equal(obj.state.shift,'14-22','backwards navigation must switch back to afternoon team');
 assert.equal(obj.selectedSlot.value.start,hour17);
 const hour22=planner.makeSlots(day,'18-06')[4].start;
 assert.equal(obj.chooseSharedHour(hour22),true);
 assert.equal(obj.state.shift,'18-06');
 const before=JSON.stringify(obj.state.shiftTeams);
 obj.chooseSharedHour(hour17);
 assert.equal(JSON.stringify(obj.state.shiftTeams),before,'navigation never edits the data');
 assert.match(html,/hour\.shifts\.includes\(item\.value\)/);
 assert.doesNotMatch(css,/#app \.obs-day-teams\{[^}]*border-top:1px/);
 assert.match(sw,/shared-hours-20261117-2/);
 console.log('PASS: shared team highlight, forward/backward auto shift switching, night hours, unchanged team data');
}finally{global.setInterval=oldTimer;}
