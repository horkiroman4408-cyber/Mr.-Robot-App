'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),vm=require('vm');
const p=require('../js/obsada-planner.js');
const day='2026-11-14',shift='18-06',login='PD009361';
let records=p.applyAssignment([],{day,shift,from:0,to:4,login,process:'AUDYT'});
records=p.applyAssignment(records,{day,shift,from:4,to:12,login,process:'METKI'});
assert.equal(records.length,12);
const slots=p.makeSlots(day,shift);
assert.equal(slots.length,12);
const now=slots[5].start+30*60000;
assert.equal(p.finishedHourCount(records,now),5,'only 5 fully finished hours at 23:30');
assert.equal(records.filter(r=>p.autoHourConfirmed(r,now)&&r.process==='AUDYT').length,4);
assert.equal(records.filter(r=>p.autoHourConfirmed(r,now)&&r.process==='METKI').length,1);
assert.equal(records.filter(r=>!p.autoHourConfirmed(r,now)&&r.process==='METKI').length,7);
assert.equal(p.finishedHourCount(records,slots[11].end),12,'all hours finished by 06:00 next day');
assert.equal(p.finishedHourCount(records,slots[0].end-1),0,'hour does not finish early');
const vmContext={console,setTimeout,clearTimeout,Uint8Array,ArrayBuffer,Date};
vm.runInNewContext(fs.readFileSync(__dirname+'/../js/xlsx.js','utf8'),vmContext,{timeout:12000});
const XLSX=vmContext.XLSX;
const ancient=p.applyAssignment([],{day:'2020-11-14',shift,from:0,to:2,login,process:'AUDYT'});
const future=p.applyAssignment([],{day:'2099-11-14',shift,from:0,to:2,login,process:'METKI'});
const wb=p.buildWorkbook(XLSX,[...ancient,...future],[],[],{},null);
const statuses=XLSX.utils.sheet_to_json(wb.Sheets.PRZYDZIALY,{header:1}).slice(1).map(row=>row[6]);
assert.deepEqual(Array.from(statuses),['POTWIERDZONE_AUTO','POTWIERDZONE_AUTO','PLAN','PLAN']);
const rt=p.readDatabase(XLSX,XLSX.read(XLSX.write(wb,{type:'array',bookType:'xlsx'}),{type:'array'}));
assert.equal(rt.records.length,4);
assert.equal(rt.records[0].process,'AUDYT');
console.log('PASS: per-hour automatic status, midnight, actual XLSX, no premature confirmation');
