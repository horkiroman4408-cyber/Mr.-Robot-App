'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.join(__dirname,'..');
const source=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
const begin=source.indexOf('// Remember the last chosen Obsada (read-only staffing)');
const end=source.indexOf('// Warn when local changes',begin);
assert(begin>0&&end>begin,'The actual application must contain the view persistence code');
const snippet=source.slice(begin,end);
const KEY='mrrobot-obsada-view-selection-v1';
function load(storage,tab='today'){
 const handlers=[];
 const store={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
 const obsada={state:{tab}};
 const state={day:'2026-11-15',shift:'06-18',from:0,to:1};
 const obsadaPlan={state,shifts:[{value:'06-18'},{value:'18-06'},{value:'06-14'}],get slots(){return Array.from({length:state.shift==='06-14'?8:12},(_,index)=>({index}));}};
 const Vue={watch:(getter,fn,options={})=>{handlers.push({getter,fn});if(options.immediate)fn(getter());}};
 vm.runInNewContext(snippet,{obsada,obsadaPlan,Vue,window:{localStorage:store},JSON,Number});
 const update=()=>handlers[1].fn(handlers[1].getter());
 const changeTab=next=>{const previous=obsada.state.tab;obsada.state.tab=next;handlers[0].fn(next,previous);};
 return {state,changeTab,update,store};
}
const memory=new Map();
const a=load(memory);
a.state.day='2026-11-14';a.state.shift='18-06';a.state.from=7;a.state.to=8;a.update();
assert.deepEqual(JSON.parse(memory.get(KEY)),{day:'2026-11-14',shift:'18-06',from:7});
a.changeTab('planning');a.state.day='2026-11-20';a.state.shift='06-14';a.state.from=2;a.update();
assert.deepEqual(JSON.parse(memory.get(KEY)),{day:'2026-11-14',shift:'18-06',from:7},'Planning must not overwrite staffing view preference');
a.changeTab('today');assert.deepEqual({...a.state},{day:'2026-11-14',shift:'18-06',from:7,to:8});
const b=load(memory);assert.deepEqual({...b.state},{day:'2026-11-14',shift:'18-06',from:7,to:8},'Saved view must restore after reload');
const cMemory=new Map([[KEY,JSON.stringify({day:'incorrect',shift:'unknown',from:999})]]);
const c=load(cMemory);assert.equal(c.state.shift,'06-18');assert.equal(c.state.from,0);
