'use strict';
const assert=require('node:assert/strict');
const fs=require('fs');const vm=require('vm');
const p=require('../js/obsada-planner.js');
const ctx={console,setTimeout,clearTimeout,Uint8Array,ArrayBuffer,Date};
vm.runInNewContext(fs.readFileSync(__dirname+'/../js/xlsx.js','utf8'),ctx,{timeout:10000});
const XLSX=ctx.XLSX;
const stan={updatedAt:'2026-11-15T12:34:00.000Z',intervals:[{label:'06:00-07:00',people:[{login:'36001118',process:'AUDYT'},{login:'36001119',process:'METKI'}]},{label:'07:00-08:00',people:[{login:'36001118',process:'METKI'}]}]};
const team={'2026-11-14|18-06':['36001118']};
const records=p.applyAssignment([],{day:'2026-11-14',shift:'18-06',from:0,to:2,login:'36001118',process:'AUDYT'});
const history=[{date:'2026-11-05',login:'36001118',process:'SCALANIE',hours:8,source:'Listopad',sourceType:'main',raw:'SCALANIE (8h)'}];
const original=p.buildWorkbook(XLSX,records,history,[],team,stan);
assert.ok(original.Sheets.STAN_SNAPSHOT);
const output=XLSX.write(original,{type:'array',bookType:'xlsx'});
const restored=p.readDatabase(XLSX,XLSX.read(output,{type:'array',cellDates:false}));
assert.equal(restored.records.length,2);
assert.equal(restored.history.length,1);
assert.equal(restored.stan.intervals.length,2);
assert.equal(restored.stan.intervals[0].people[0].login,'36001118');
assert.equal(restored.stan.updatedAt,stan.updatedAt);
assert.deepEqual(restored.shiftTeams['2026-11-14|18-06'],team['2026-11-14|18-06']);
const old=p.buildWorkbook(XLSX,records,history,[],team);
assert.equal(p.readDatabase(XLSX,old).stan,null,'legacy database must remain readable');
console.log('PASS SharePoint STAN snapshot + history + planning XLSX roundtrip; legacy compatibility');
