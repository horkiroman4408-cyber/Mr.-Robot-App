const assert=require('node:assert/strict');
const p=require('../js/obsada-planner.js');
const unified=require('../js/obsada-unified-history.js');
const vm=require('vm'),fs=require('fs'),path=require('path');
const context={console,Uint8Array,ArrayBuffer,Date};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../js/xlsx.js'),'utf8'),context);
const xlsx=context.XLSX;
const hours=p.makeSlots('2026-11-15','18-06');
assert.equal(hours.length,12);
assert.deepEqual(p.absenceDates('2026-11-15','2026-11-17'),['2026-11-15','2026-11-16','2026-11-17']);
assert.throws(()=>p.absenceDates('2026-02-30','2026-03-01'),/INVALID_ABSENCE_RANGE/);
assert.throws(()=>p.absenceDates('2026-11-20','2026-11-15'),/INVALID_ABSENCE_RANGE/);
assert.equal(p.absenceDates('2028-02-28','2028-03-01').length,3);
let rows=p.assignFromHour([],{day:'2026-11-15',shift:'18-06',from:0,login:'PD001',process:'AUDYT'});
const cut=p.cutAfterHour(rows,{day:'2026-11-15',shift:'18-06',login:'PD001',from:5});
assert.equal(cut.length,5);assert.equal(cut[0].process,'AUDYT');assert.equal(cut[4].slot,4);
const statuses=p.updateLocalAbsences([{date:'2026-11-15',login:'PD001',status:'WOLNY',source:'SharePoint'}],['PD001','PD002'],['2026-11-15'],'URLOP');
assert.equal(statuses.filter(x=>x.status==='URLOP').length,2);
assert.equal(statuses.filter(x=>x.source==='SharePoint').length,1);
const twice=p.updateLocalAbsences(statuses,['PD001','PD002'],['2026-11-15'],'URLOP');
assert.equal(twice.length,statuses.length);
const workbook=p.buildWorkbook(xlsx,cut,[],twice);
const back=p.readDatabase(xlsx,workbook);
assert.equal(back.records.length,5);assert.equal(back.statuses.length,3);
const result=unified.resolve({history:[{date:'2026-11-15',login:'PD002',process:'AUDYT',hours:12,source:'SharePoint'}],statuses:twice,records:cut,now:Date.parse('2026-11-17'),isConfirmed:p.autoHourConfirmed,isExcluded:()=>false,makeSlots:p.makeSlots});
assert(result.rows.some(r=>r.login==='PD002'&&r.kind==='work'&&r.superseded),'local URLOP supersedes imported work in counted totals');
assert(result.rows.some(r=>r.login==='PD002'&&r.kind==='status'&&r.process==='URLOP'));
assert(!result.discrepancies.some(r=>r.login==='PD002'));
console.log('PASS worker absence/date range/departure/XLSX/local priority');
