'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const merge=require('../js/obsada-merge.js'),planner=require('../js/obsada-planner.js');
const ctx={console,setTimeout,clearTimeout,Date,Uint8Array,ArrayBuffer};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../js/xlsx.js'),'utf8'),ctx,{timeout:20000});
const XLSX=ctx.XLSX;
const day='2026-11-13',shift='18-06';
const row=(slot,process,login='PD1',updated='2026-11-14T08:00:00Z')=>({day,shift,slot,login,process,updated});
const local={records:[row(0,'AUDYT'),row(1,'AUDYT')],history:[{date:day,login:'PD1',process:'METKI',hours:12,source:'Listopad',sourceType:'main',raw:'METKI (12h)'}],statuses:[{date:'2026-11-12',login:'PD1',status:'WOLNY',source:'Listopad'}],shiftTeams:{[`${day}|${shift}`]:['PD1']},teamTemplates:{INCYDENTY:['PD1']},stan:null,hiddenProcesses:[],excludedHistory:[],confirmations:{},tombstones:[]};
const remote={...local,records:[row(0,'METKI'),row(1,'AUDYT'),row(2,'METKI','PD2')],shiftTeams:{[`${day}|${shift}`]:['PD1','PD2']},teamTemplates:{INCYDENTY:['PD1','PD2']},statuses:[...local.statuses,{date:'2026-11-11',login:'PD2',status:'URLOP',source:'Listopad'}]};
let m=merge.plan(local,remote);
assert.equal(m.counts.newAssignments,1);
assert.equal(m.counts.newStatuses,1);
assert.ok(m.conflicts.some(x=>x.kind==='assignment'));
assert.ok(m.conflicts.some(x=>x.kind==='shiftTeams'));
let result=m.apply();assert.equal(result.records.find(x=>x.slot===0).process,'AUDYT');
const selected=Object.fromEntries(m.conflicts.map(x=>[x.id,'theirs']));result=m.apply(selected);
assert.equal(result.records.find(x=>x.slot===0).process,'METKI');
assert.deepEqual(result.teamTemplates.INCYDENTY,['PD1','PD2']);
assert.equal(result.statuses.length,2);
const repeated=merge.plan(result,remote).apply();assert.equal(repeated.records.length,3);assert.equal(repeated.statuses.length,2);
const deleted=merge.plan({...local,records:[],tombstones:[{key:merge.key(row(0,'AUDYT')),at:'2026-11-15T12:00:00Z'}]},remote).apply();
assert.ok(!deleted.records.some(x=>x.slot===0),'delete marker prevents resurrection from older database');
const book=planner.buildWorkbook(XLSX,result.records,result.history,result.statuses,result.shiftTeams,result.stan,result.hiddenProcesses,result.confirmations,result.excludedHistory,result.teamTemplates,[{key:merge.key(row(9,'OLD')),at:'2026-11-15T12:00:00Z'}]);
const parsed=planner.readDatabase(XLSX,XLSX.read(XLSX.write(book,{type:'array',bookType:'xlsx'}),{type:'array'}));
assert.equal(parsed.records.length,3);assert.equal(parsed.statuses.length,2);assert.equal(parsed.tombstones.length,1);
assert.deepEqual(parsed.teamTemplates.INCYDENTY,['PD1','PD2']);
const old=planner.readDatabase(XLSX,planner.buildWorkbook(XLSX,[],[],[],{},null,[],{},[],{}));
assert.equal(old.tombstones.length,0);
const index=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
assert.ok(index.includes('previewColleagueFile($event)'));
assert.ok(index.includes('js/obsada-merge.js'));
const sw=fs.readFileSync(path.join(__dirname,'../sw.js'),'utf8');
assert.ok(sw.includes('js/obsada-merge.js?v=3.25.0-obsada-file-exchange-1'));
console.log('PASS: whole-database merge, per-record conflicts, repeat import, tombstones, XLSX compatibility');
