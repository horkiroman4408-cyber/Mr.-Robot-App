'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const planner=require('../js/obsada-planner.js');
const release=vm.runInNewContext(fs.readFileSync(path.join(root,'js/changelog.js'),'utf8')+'\nCHANGELOG_ALL');
assert.match(html,/<title>Mr\. Robot v3\.26\.0<\/title>/);
assert.match(html,/class="settings-version"[^>]*>v3\.26\.0<\/span>/);
assert.match(sw,/CACHE_REVISION = 'v3\.26\.0/);
assert.equal(release[0].version,'3.26.0');
assert.equal(release[1].version,'3.25.0');
assert.equal(release[1].changes.length,14);
const planning=html.slice(html.indexOf('<template v-else-if="obsada.state.tab===\'planning\'">'),html.indexOf('<section v-else class="obs-surface">'));
assert.equal((planning.match(/class="obs-day-teams-add"/g)||[]).length,1);
assert.ok(planning.includes('obs-day-roster-editor'));
assert.ok(planning.includes('obs-day-roster-members'));
assert.ok(planning.includes('@click="obsadaPlan.removeTeamMember(login)"'));
assert.ok(!planning.includes('obs-plan-parallel-adding'));
assert.ok(!planning.includes('obs-plan-undobutton'));
assert.equal((planning.match(/class="obs-plan-teamadd-btn"/g)||[]).length,1);
const staffSide=planning.slice(planning.indexOf('<aside class="obs-plan-staffside">'),planning.indexOf('obs-plan-stafflist'));
assert.ok(!staffSide.includes('obs-plan-teamadd-btn'));
const oldInterval=global.setInterval;
global.setInterval=()=>0;
const instance=planner.create({reactive:x=>x,computed:f=>({get value(){return f()}}),source:()=>({employees:[],intervals:[]}),sourceName:()=>'',roster:()=>['ABC'],language:()=> 'en'});
instance.state.day='2020-11-17'; instance.state.shift='18-06';
instance.state.shiftTeams={'2020-11-17|18-06':['ABC']};
instance.state.records=planner.applyAssignment([],{day:'2020-11-17',shift:'18-06',from:0,to:2,login:'ABC',process:'AUDYT'});
Promise.resolve(instance.removeTeamMember('ABC')).then(result=>{
 assert.equal(result,false);
 assert.equal(instance.state.error,'TEAM_MEMBER_HAS_COMPLETED_HOURS');
 assert.equal(instance.state.records.length,2);
 assert.deepEqual(instance.state.shiftTeams['2020-11-17|18-06'],['ABC']);
 console.log('PASS v3.26.0 version, changelog split, no duplicate controls, protected confirmed hours');
}).catch(error=>{console.error(error);process.exitCode=1}).finally(()=>{global.setInterval=oldInterval});
