'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),vm=require('vm'),path=require('path');
const m=require('../js/obsada-planner.js');
const app=fs.readFileSync(path.resolve(__dirname,'../js/app.js'),'utf8');
const start=app.indexOf('const obsadaUnified=computed(()=>');
const end=app.indexOf('const obsadaHistoryTable=',start);
assert.ok(start>0&&end>start);
const block=app.slice(start,end);
const day='2026-11-13',login='PD009361';
const historical=[{date:day,login,process:'AUDYT',hours:12,source:'Listopad',sourceType:'main'},{date:day,login:'PD2',process:'SCALANIE',hours:8,source:'Listopad',sourceType:'main'}];
const records=[...Array.from({length:4},(_,slot)=>({day,shift:'18-06',slot,login,process:'AUDYT'})),...Array.from({length:8},(_,i)=>({day,shift:'18-06',slot:4+i,login,process:'METKI'})),{day,shift:'18-06',slot:0,login:'PD3',process:'METKI'}];
const state={records,importedHistory:historical,importedStatuses:[],excludedHistory:[]};
const obsada={state:{model:null,source:'verified',month:'',employee:'',process:''}};
const computed=fn=>({get value(){return fn();}});
const analyze=rows=>{const by=new Map();for(const r of rows)by.set(r.process,(by.get(r.process)||0)+r.hours);return {hours:rows.reduce((n,r)=>n+r.hours,0),entries:rows.length,workerDays:new Set(rows.map(r=>r.login+'|'+r.date)).size,processes:[...by]};};
const now=m.makeSlots(day,'18-06')[5].start+30*60000;
const obsadaPlan={state,clockNow:now,isExcluded:()=>false};
const obsadaHistoryOptions={planStatus:'all',sourceDetail:'all',showExcluded:false};
const sandbox={obsada,obsadaPlan,obsadaHistoryOptions,obsadaHistoryFocus:{date:'',login:''},computed,window:{ObsadaParser:{analyze},MRObsadaPlanner:m,MRObsadaUnifiedHistory:require('../js/obsada-unified-history.js')},console};
vm.createContext(sandbox);
vm.runInContext(block+'\nglobalThis.results={all:obsadaHistoryAll,filtered:obsadaHistoryFiltered,report:obsadaHistoryReport};',sandbox);
assert.equal(sandbox.results.report.value.hours,14,'6 completed hours including PD3 + 8 imported, no double count');
assert.equal(sandbox.results.all.value.filter(r=>r.kind==='confirmed').reduce((n,r)=>n+r.hours,0),6);
assert.equal(sandbox.results.all.value.filter(r=>r.kind==='plan').reduce((n,r)=>n+r.hours,0),7);
assert.ok(sandbox.results.all.value.some(r=>r.origin==='import'&&r.login===login&&r.superseded));
assert.equal(sandbox.results.report.value.processes.find(x=>x[0]==='AUDYT')[1],4);
assert.equal(sandbox.results.report.value.processes.find(x=>x[0]==='METKI')[1],2);
obsada.state.source='planning';
assert.equal(sandbox.results.report.value.hours,13,'planning view includes both elapsed and future hours');
obsadaHistoryOptions.planStatus='confirmed';
assert.equal(sandbox.results.report.value.hours,6,'only elapsed hours with completed filter');
console.log('PASS: hours confirmed as elapsed, future hours separate, SharePoint overlap excluded');
