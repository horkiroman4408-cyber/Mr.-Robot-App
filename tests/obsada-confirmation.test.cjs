'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),vm=require('vm'),path=require('path');
const p=require('../js/obsada-planner.js');
const ctx={console,setTimeout,clearTimeout,Uint8Array,ArrayBuffer,Date};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../js/xlsx.js'),'utf8'),ctx,{timeout:12000});
const XLSX=ctx.XLSX;
const past=p.applyAssignment([],{day:'2020-11-13',shift:'18-06',from:0,to:2,login:'PD009361',process:'AUDYT'});
const future=p.applyAssignment([],{day:'2099-11-13',shift:'18-06',from:0,to:2,login:'PD009361',process:'METKI'});
const history=[{date:'2020-11-13',login:'PD009361',process:'AUDYT',hours:12,source:'Listopad',sourceType:'main',raw:'AUDYT (12h)'}];
const wb=p.buildWorkbook(XLSX,[...past,...future],history);
const statuses=Array.from(XLSX.utils.sheet_to_json(wb.Sheets.PRZYDZIALY,{header:1}).slice(1).map(row=>row[6]));
assert.deepEqual(statuses,['POTWIERDZONE_AUTO','POTWIERDZONE_AUTO','PLAN','PLAN']);
const rt=p.readDatabase(XLSX,XLSX.read(XLSX.write(wb,{type:'array',bookType:'xlsx'}),{type:'array'}));
assert.equal(rt.records.length,4);
assert.equal(rt.history.length,1);
assert.equal(rt.history[0].hours,12);
assert.deepEqual(rt.confirmations,{});
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
assert.ok(!html.includes('obsadaPlan.confirmShift()'));
assert.ok(!html.includes('obsadaPlan.unlockShift()'));
assert.ok(!html.includes('obsadaPlan.finishedHours }} h'),'Planning must not display total elapsed/planned hours');
assert.ok(html.includes('obsadaPlan.currentPeopleCount'),'Planning must retain selected-hour staffing count');
console.log('PASS: time-derived XLSX status and no manual confirmation UI');
