'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const p=require('../js/obsada-planner.js');
// The repository's bundled SheetJS is used for a genuine XLSX round trip.
const vm=require('node:vm');const ctx={console,setTimeout,clearTimeout,Uint8Array,ArrayBuffer,Date};vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../js/xlsx.js'),'utf8'),ctx,{timeout:12000});const XLSX=ctx.XLSX;
const prior=[{day:'2026-11-13',shift:'18-06',slot:0,login:'PD009361',process:'AUDYT'},{day:'2026-11-13',shift:'18-06',slot:4,login:'PD009361',process:'METKI'}];
const confirmed={'2026-11-13|18-06':'2026-11-14T06:20:00.000Z'};
const historical=[{date:'2026-11-13',login:'PD009361',process:'AUDYT',hours:12,source:'Listopad',sourceType:'main',raw:'AUDYT (12h)'}];
const wb=p.buildWorkbook(XLSX,prior,historical,[],{'2026-11-13|18-06':['PD009361']},null,[],confirmed);
assert.ok(wb.SheetNames.includes('POTWIERDZENIA'));
const statuses=XLSX.utils.sheet_to_json(wb.Sheets.PRZYDZIALY,{header:1}).slice(1).map(row=>row[6]);
assert.equal(JSON.stringify(statuses),JSON.stringify(['POTWIERDZONE','POTWIERDZONE']));
const binary=XLSX.write(wb,{type:'array',bookType:'xlsx'});
const read=p.readDatabase(XLSX,XLSX.read(binary,{type:'array',cellDates:false}));
assert.deepEqual(read.confirmations,confirmed);
assert.equal(read.records.length,2);
assert.equal(read.history.length,1);
assert.equal(read.history[0].hours,12);
const old=p.readDatabase(XLSX,XLSX.read(XLSX.write(p.buildWorkbook(XLSX,prior,historical),{type:'array',bookType:'xlsx'}),{type:'array'}));
assert.deepEqual(old.confirmations,{});
const slots=p.makeSlots('2026-11-13','18-06');
assert.equal(new Date(slots[0].start).getDate(),13);
assert.equal(new Date(slots.at(-1).end).getDate(),14);
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
assert.ok(html.includes('obsadaPlan.confirmShift()'));
assert.ok(html.includes('obsadaPlan.unlockShift()'));
assert.ok(app.includes("r.kind==='confirmed'"));
assert.ok(app.includes('r.superseded'));
assert.ok(app.includes('confirmedPeople'));
console.log('Obsada confirmation XLSX, legacy, overnight shifts and UI/analytics contracts PASS');
