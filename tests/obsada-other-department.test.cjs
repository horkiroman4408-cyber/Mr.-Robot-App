'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const P=require('../js/obsada-planner.js');
const day='2026-11-16';
let records=[];
for(const [login,shift,process] of [['A','18-06','AUDYT'],['B','14-22','PICK'],['C','14-22','PACK'],['D','18-06','METKI'],['E','14-22','ZWROTY'],['F','14-22','WYSYŁKA']])
 records=P.assignFromHour(records,{day,shift,from:0,login,process});
const stamp=P.makeSlots(day,'18-06')[1].start;
const raw=P.rosterAtTimestamp(records,stamp);
const source=JSON.stringify(records);
const xlsx=JSON.stringify(P.sheetRows(records).assignments);
assert.equal(raw.count,6);
const selected=['PACK','PICK','ZWROTY','WYSYŁKA'];
let split=P.splitRosterDepartments(raw,selected);
assert.equal(split.local.count,2);
assert.equal(split.other.count,4);
assert.equal(split.local.processCount,2);
assert.equal(split.other.processCount,4);
assert.deepEqual(split.other.groups.map(g=>g.name).sort(),selected.sort());
assert.equal(split.local.count+split.other.count,raw.count);
// Moving a card only changes its visual grouping; hours and assignments stay identical.
split=P.splitRosterDepartments(raw,['PICK','PACK','ZWROTY','WYSYŁKA','METKI']);
assert.equal(split.other.count,5);assert.equal(split.local.count,1);
split=P.splitRosterDepartments(raw,['PACK','ZWROTY','WYSYŁKA']);
assert.equal(split.other.count,3);assert.equal(split.local.count,3);
assert.equal(JSON.stringify(records),source);
assert.equal(JSON.stringify(P.sheetRows(records).assignments),xlsx);
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const js=fs.readFileSync(path.join(__dirname,'..','js','obsada-planner.js'),'utf8');
assert.match(html,/readonlyRoster\.count/);
assert.match(html,/readonlyDepartments\.local\.count/);
assert.match(html,/readonlyDepartments\.other\.count/);
assert.match(html,/obsadaPlan\.startDepartmentDrag\(\$event,item\.name\)/);
assert.match(html,/obsadaPlan\.dropDepartmentCard\(\$event,'local'\)/);
assert.match(html,/obsadaPlan\.dropDepartmentCard\(\$event,'other'\)/);
assert.match(html,/setOtherDepartmentProcess\(item\.name,true\)/);
assert.match(html,/setOtherDepartmentProcess\(item\.name,false\)/);
assert.doesNotMatch(html,/obsadaPlan\.state\.otherDepartmentSettingsOpen/);
assert.match(js,/state\.departmentDragProcess===key/);
console.log('PASS: card movement, default categories, totals, unchanged assignments and XLSX');
