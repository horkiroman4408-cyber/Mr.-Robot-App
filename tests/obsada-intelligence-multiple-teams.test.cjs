'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const base=__dirname+'/..';
const app=fs.readFileSync(base+'/js/app.js','utf8');
const html=fs.readFileSync(base+'/index.html','utf8');
const start=app.indexOf('function obsadaTeamSyncSelection()');
const end=app.indexOf('function obsadaTeamDayStatus(',start);
assert(start>0&&end>start);
const state={selected:[],selectedTemplates:[],manualSelected:[],excluded:[],templateChoice:'',chooserOpen:true};
const templates={'INCYDENTY':['A','B','C'],'INCYDENTY-LPP':['C','D','E']};
const ctx={obsadaTeam:state,obsadaPlan:{state:{teamTemplates:templates},team:['X','Y']}};
vm.createContext(ctx);
vm.runInContext(app.slice(start,end)+';globalThis.api={add:obsadaTeamSelectTemplate,remove:obsadaTeamRemoveTemplate,clear:obsadaTeamClear,toggle:obsadaTeamToggle,shift:obsadaTeamAddShift};',ctx);
const {add,remove,clear,toggle,shift}=ctx.api;
state.templateChoice='INCYDENTY';add();assert.deepEqual([...state.selected],['A','B','C']);assert.equal(state.templateChoice,'');
state.templateChoice='INCYDENTY-LPP';add();assert.deepEqual([...state.selected],['A','B','C','D','E']);assert.equal(state.selectedTemplates.length,2);
state.templateChoice='INCYDENTY';add();assert.equal(state.selectedTemplates.length,2,'repeat team ignored');
toggle('C');assert.deepEqual([...state.selected],['A','B','D','E'],'individual removal excludes overlap');
toggle('Z');assert.deepEqual([...state.selected],['Z','A','B','D','E'],'manual additions preserved');
remove('INCYDENTY');assert.deepEqual([...state.selected],['Z','D','E'],'other team stays; C excluded');
state.templateChoice='INCYDENTY';add();assert.deepEqual(new Set(state.selected),new Set(['Z','D','E','A','B','C']),'re-adding team restores its members');
remove('INCYDENTY-LPP');assert.deepEqual([...state.selected],['Z','A','B','C'],'shared worker remains from other team');
clear();assert.deepEqual([...state.selected],[]);assert.deepEqual([...state.selectedTemplates],[]);
state.templateChoice='INCYDENTY';add();shift();assert.deepEqual([...state.selected],['X','Y'],'current shift resets multi-team selection');
assert.match(html,/obs-team-intel-team-tags/);assert.match(html,/obsadaTeamRemoveTemplate\(name\)/);
assert.match(html,/obsadaTeamClear\(\)/);
assert.match(html,/js\/app\.js\?v=3\.25\.0-intelligence-multiteam-1/);
console.log('PASS: two teams, overlap deduplication, manual edits, team removal, reset, current shift and UI');
