'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),vm=require('vm');
const planner=require('../js/obsada-planner.js');
const ctx={console,setTimeout,clearTimeout,Uint8Array,ArrayBuffer,Date};
vm.runInNewContext(fs.readFileSync(__dirname+'/../js/xlsx.js','utf8'),ctx,{timeout:10000});
const XLSX=ctx.XLSX;
const day='2026-11-14',shift='18-06',login='36001118';
const records=planner.applyAssignment([],{day,shift,from:0,to:4,login,process:'AUDYT'});
assert.equal(records.length,4);
assert.equal(planner.dropAssignments(records,{day,shift,login,from:1,to:2}).length,3);
assert.equal(planner.dropAssignments(records,{day,shift,login,from:0,to:4}).length,0);
const team={[day+'|'+shift]:[login,'36001119']};
const history=[{date:'2026-11-01',login,process:'SCALANIE',hours:8,source:'Listopad',sourceType:'main',raw:'SCALANIE (8h)'}];
const statuses=[{date:'2026-11-02',login,status:'WOLNY',source:'Listopad'}];
const wb=planner.buildWorkbook(XLSX,records,history,statuses,team);
assert.deepEqual([...wb.SheetNames].sort(),['PRZYDZIALY','ZMIANY','HISTORIA_IMPORTOWANA','STATUSY','ZESPOLY','STAN_SNAPSHOT','PROCESY_UKRYTE','POTWIERDZENIA','WYKLUCZENIA','INFO'].sort());
const bytes=XLSX.write(wb,{type:'array',bookType:'xlsx'});
const rt=planner.readDatabase(XLSX,XLSX.read(bytes,{type:'array',cellDates:false}));
assert.equal(rt.records.length,4);
assert.equal(rt.history.length,1);
assert.equal(rt.statuses.length,1);
assert.deepEqual(rt.shiftTeams[day+'|'+shift],team[day+'|'+shift]);
assert.equal(rt.records[0].process,'AUDYT');
console.log('PASS Obsada teams, four-hour assignment, range removal, XLSX roundtrip');
